import {readFile} from 'node:fs/promises';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {collection,doc,getDoc,getDocs,setDoc,updateDoc,deleteDoc,query,limit,serverTimestamp,Timestamp} from 'firebase/firestore';
const projectId='demo-rainbow-classroom';
if(!process.env.FIRESTORE_EMULATOR_HOST)throw Error('Run only through firebase emulators:exec; production tests are forbidden.');
const environment=await initializeTestEnvironment({projectId,firestore:{rules:await readFile(new URL('../firestore.rules',import.meta.url),'utf8')}});
let count=0;
const google={email_verified:true,firebase:{sign_in_provider:'google.com'}};
const alice=environment.authenticatedContext('alice',google).firestore();
const bob=environment.authenticatedContext('bob',google).firestore();
const admin=environment.authenticatedContext('teacher',google).firestore();
const unverified=environment.authenticatedContext('alice',{...google,email_verified:false}).firestore();
const anonymous=environment.unauthenticatedContext().firestore();
const entry=()=>({date:'2026-10-17',title:'Synthetic',content:'No personal data',mood:'평온',createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
const program=()=>({title:'Math',description:'Synthetic public tool',url:'https://example.com/',created_at:serverTimestamp(),updated_at:serverTimestamp()});
async function ok(operation){await assertSucceeds(operation);count++;}
async function no(operation){await assertFails(operation);count++;}
try{
 await environment.clearFirestore();
 await environment.withSecurityRulesDisabled(async context=>{await setDoc(doc(context.firestore(),'admin_users','teacher'),{enabled:true});});
 await ok(setDoc(doc(alice,'users/alice/entries/one'),entry()));
 await ok(getDoc(doc(alice,'users/alice/entries/one')));
 await ok(getDocs(query(collection(alice,'users/alice/entries'),limit(500))));
 await no(getDocs(collection(alice,'users/alice/entries')));
 await no(getDoc(doc(bob,'users/alice/entries/one')));
 await no(getDocs(query(collection(bob,'users/alice/entries'),limit(500))));
 await no(updateDoc(doc(bob,'users/alice/entries/one'),{content:'forbidden',updatedAt:serverTimestamp()}));
 await no(deleteDoc(doc(bob,'users/alice/entries/one')));
 await no(getDoc(doc(anonymous,'users/alice/entries/one')));
 await no(getDoc(doc(unverified,'users/alice/entries/one')));
 await no(getDoc(doc(admin,'users/alice/entries/one')));
 await ok(updateDoc(doc(alice,'users/alice/entries/one'),{content:'Edited',updatedAt:serverTimestamp()}));
 await no(updateDoc(doc(alice,'users/alice/entries/one'),{createdAt:Timestamp.fromMillis(0),updatedAt:serverTimestamp()}));
 await no(updateDoc(doc(alice,'users/alice/entries/one'),{owner:'bob',updatedAt:serverTimestamp()}));
 await no(setDoc(doc(alice,'users/alice/entries/bad'),{...entry(),title:''}));
 await no(setDoc(doc(alice,'users/alice/entries/bad'),{...entry(),content:'x'.repeat(30001)}));
 await no(setDoc(doc(alice,'users/alice/entries/bad'),{...entry(),mood:'unknown'}));
 await no(setDoc(doc(alice,'users/alice/entries/bad'),{...entry(),date:'2026-99-99'}));
 await no(setDoc(doc(alice,'admin_users/alice'),{enabled:true}));
 await no(setDoc(doc(alice,'programs/tool'),program()));
 await no(setDoc(doc(anonymous,'programs/tool'),program()));
 await ok(setDoc(doc(admin,'programs/tool'),program()));
 await ok(getDoc(doc(anonymous,'programs/tool')));
 await ok(getDocs(query(collection(anonymous,'programs'),limit(100))));
 await no(getDocs(collection(anonymous,'programs')));
 await no(getDocs(query(collection(anonymous,'programs'),limit(101))));
 await no(setDoc(doc(admin,'programs/bad'),{...program(),url:'javascript:alert(1)'}));
 await no(setDoc(doc(admin,'programs/bad'),{...program(),url:'https://user:pass@example.com/'}));
 await no(setDoc(doc(admin,'programs/bad'),{...program(),extra:'forbidden'}));
 await ok(updateDoc(doc(admin,'programs/tool'),{title:'Updated',updated_at:serverTimestamp()}));
 await no(updateDoc(doc(admin,'programs/tool'),{created_at:Timestamp.fromMillis(0),updated_at:serverTimestamp()}));
 await no(getDocs(collection(alice,'admin_users')));
 await ok(getDoc(doc(admin,'admin_users/teacher')));
 await no(getDoc(doc(alice,'admin_users/teacher')));
 await ok(deleteDoc(doc(admin,'programs/tool')));
 await environment.withSecurityRulesDisabled(async context=>{await updateDoc(doc(context.firestore(),'admin_users/teacher'),{enabled:false});});
 await no(setDoc(doc(admin,'programs/revoked'),program()));
 await ok(deleteDoc(doc(alice,'users/alice/entries/one')));
 console.log(`PASS: ${count} Firestore access assertions (isolated emulator only)`);
}finally{await environment.cleanup();}
